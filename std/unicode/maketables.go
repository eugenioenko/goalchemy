//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"unicode"
)

func ranges(name string, is func(rune) bool, b *bytes.Buffer) {
	var rs []rune
	in := false
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		p := r <= unicode.MaxRune && is(r)
		if p != in {
			if p {
				rs = append(rs, r)
			} else {
				rs = append(rs, r-1)
			}
			in = p
		}
	}
	list(name, rs, b)
}

func list(name string, rs []rune, b *bytes.Buffer) {
	fmt.Fprintf(b, "const %s = \"\" +", name)
	for i, r := range rs {
		if i%16 == 0 {
			b.WriteString("\n\t\"")
		}
		fmt.Fprintf(b, "\\x%02x\\x%02x\\x%02x", byte(r>>16), byte(r>>8), byte(r))
		if i%16 == 15 || i == len(rs)-1 {
			b.WriteString("\" +")
		}
	}
	b.WriteString("\n\t\"\"\n\n")
}

func fallbackFold(r rune) rune {
	if l := unicode.ToLower(r); l != r {
		return l
	}
	return unicode.ToUpper(r)
}

func main() {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run maketables.go. DO NOT EDIT.\n\npackage unicode\n\n")
	fmt.Fprintf(&b, "// Version is the Unicode edition the tables are derived from.\nconst Version = %q\n\n", unicode.Version)
	b.WriteString("// Tables pack runes as 3 big-endian bytes. Range tables hold inclusive\n// [lo, hi] pairs.\n")
	ranges("letterTable", unicode.IsLetter, &b)
	ranges("upperTable", unicode.IsUpper, &b)
	ranges("lowerTable", unicode.IsLower, &b)
	ranges("titleTable", unicode.IsTitle, &b)
	ranges("digitTable", unicode.IsDigit, &b)
	ranges("numberTable", unicode.IsNumber, &b)
	ranges("punctTable", unicode.IsPunct, &b)
	ranges("symbolTable", unicode.IsSymbol, &b)
	ranges("markTable", unicode.IsMark, &b)
	ranges("controlTable", unicode.IsControl, &b)
	ranges("printTable", unicode.IsPrint, &b)
	ranges("graphicTable", unicode.IsGraphic, &b)

	// Case runs: lo, hi, and the lower, upper, and title deltas shared by
	// every rune in the run. Deltas of upperLower mark runs that alternate
	// upper and lower case starting with upper at lo.
	const upperLower = 0x7FFFFF
	var cs []rune
	alternates := func(r rune) bool {
		return unicode.ToLower(r) == r+1 && unicode.ToUpper(r) == r && unicode.ToTitle(r) == r &&
			unicode.ToLower(r+1) == r+1 && unicode.ToUpper(r+1) == r && unicode.ToTitle(r+1) == r
	}
	deltas := func(r rune) (rune, rune, rune) {
		return unicode.ToLower(r) - r, unicode.ToUpper(r) - r, unicode.ToTitle(r) - r
	}
	for r := rune(0); r <= unicode.MaxRune; {
		if alternates(r) {
			lo := r
			for r <= unicode.MaxRune-1 && alternates(r) {
				r += 2
			}
			cs = append(cs, lo, r-1, upperLower, upperLower, upperLower)
			continue
		}
		dl, du, dt := deltas(r)
		lo := r
		for r <= unicode.MaxRune && !alternates(r) {
			l, u, t := deltas(r)
			if l != dl || u != du || t != dt {
				break
			}
			r++
		}
		if dl != 0 || du != 0 || dt != 0 {
			cs = append(cs, lo, r-1, dl, du, dt)
		}
	}
	list("caseTable", cs, &b)

	var orbit []rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := unicode.SimpleFold(r); f != fallbackFold(r) {
			orbit = append(orbit, r, f)
		}
	}
	list("foldTable", orbit, &b)

	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		panic(err)
	}
}
