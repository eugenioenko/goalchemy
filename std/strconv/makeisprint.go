//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"unicode"
)

func main() {
	var lo, hi []rune
	in := false
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		p := r <= unicode.MaxRune && unicode.IsPrint(r)
		switch {
		case p && !in:
			lo = append(lo, r)
			in = true
		case !p && in:
			hi = append(hi, r-1)
			in = false
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run makeisprint.go. DO NOT EDIT.\n\npackage strconv\n\n")
	fmt.Fprintf(&b, "// Unicode %s printable ranges, inclusive.\n", unicode.Version)
	for _, t := range []struct {
		name string
		rs   []rune
	}{{"printLo", lo}, {"printHi", hi}} {
		fmt.Fprintf(&b, "var %s = []rune{", t.name)
		for i, r := range t.rs {
			if i%12 == 0 {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "%#x, ", r)
		}
		b.WriteString("\n}\n\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("isprint.go", src, 0o644); err != nil {
		panic(err)
	}
}
